// Static build: copies src/ to dist/, writes js/config.js from the deploy manifest, ships the shared
// North Score module and stamps asset URLs for cache busting. Usage: NETWORK=robinhoodTestnet node build.mjs
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync, readdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";

const NETWORK = process.env.NETWORK || "robinhoodTestnet";
// The launched $POLARIS contract address, given by the owner (never the testnet token from deployments). Empty keeps it off the site.
const POLARIS_CA = "";
const CHAINS = {
  robinhoodTestnet: {
    id: 46630, name: "Robinhood Chain Testnet", testnet: true,
    rpcs: ["https://rpc.testnet.chain.robinhood.com"],
    explorer: "https://explorer.testnet.chain.robinhood.com",
    faucet: "https://faucet.testnet.chain.robinhood.com",
  },
  robinhood: {
    id: 4663, name: "Robinhood Chain", testnet: false,
    rpcs: ["https://rpc.mainnet.chain.robinhood.com", "https://robinhood.drpc.org", "https://robinhood-rpc.publicnode.com"],
    explorer: "https://robinhoodchain.blockscout.com",
  },
  localhost: { id: 31337, name: "Local Hardhat", testnet: true, rpcs: ["http://127.0.0.1:8545"], explorer: "https://explorer.testnet.chain.robinhood.com" },
};
const chain = CHAINS[NETWORK];
if (!chain) throw new Error(`unknown NETWORK ${NETWORK}`);

const depFile = `../../packages/contracts/deployments/${NETWORK}.json`;
if (!existsSync(depFile)) throw new Error(`missing ${depFile}: deploy and verify the contracts first`);
const dep = JSON.parse(readFileSync(depFile, "utf8"));
const c = dep.contracts;

const config = {
  network: NETWORK,
  testnet: chain.testnet,
  chain: { ...chain, hex: "0x" + chain.id.toString(16) },
  api: process.env.API_BASE || "",
  deployedAt: dep.deployedAt,
  ca: NETWORK === "robinhood" && POLARIS_CA ? POLARIS_CA : null, // mainnet only: the testnet site keeps the token hidden
  // $POLARIS launches elsewhere; its address goes on the site only once that launch is live
  contracts: Object.entries(c).filter(([key]) => key !== "token").map(([key, v]) => ({ key, name: v.name, proxy: v.proxy, implementation: v.implementation, version: "1.0.0" })),
  // the vault asset is plain ERC-20 (pUSD on testnet, USDG on mainnet)
  selectors: { ...dep.selectors, ERC20: { balanceOf: "0x70a08231", allowance: "0xdd62ed3e", approve: "0x095ea7b3" } },
  beacon: c.beacon?.proxy,
  registry: c.registry?.proxy,
  asset: c.dollar ? { address: c.dollar.proxy, symbol: "pUSD", decimals: 6 } : { address: dep.asset?.address, symbol: "USDG", decimals: 6 },
  vaults: Object.entries(c)
    .filter(([k]) => k.startsWith("vault"))
    .map(([k, v]) => { const n = k.slice(5); return { key: k, address: v.proxy, name: n, symbol: "nv" + n.toUpperCase(), curator: "Polaris Labs" }; }),
};

rmSync("dist", { recursive: true, force: true });
cpSync("src", "dist", { recursive: true });
cpSync("../api/score.mjs", "dist/js/score.js");
writeFileSync("dist/js/config.js", `// generated by build.mjs for ${NETWORK}\nexport const CONFIG = ${JSON.stringify(config, null, 2)};\n`);

// cache-bust css and entry scripts referenced from html
const hash = (p) => createHash("sha256").update(readFileSync(join("dist", p))).digest("hex").slice(0, 10);
for (const f of readdirSync("dist").filter((f) => f.endsWith(".html"))) {
  const html = readFileSync(join("dist", f), "utf8").replace(/(href|src)="\/((?:css|js)\/[^"?]+)"/g, (_, a, p) => `${a}="/${p}?v=${hash(p)}"`);
  writeFileSync(join("dist", f), html);
}
mkdirSync("dist/.well-known", { recursive: true });
console.log(`built dist/ for ${NETWORK} (${config.contracts.length} contracts)`);
